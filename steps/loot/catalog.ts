/**
 * The loot pass's catalog: the fill as a builder needs it. Scratch, like the rest of this folder; it goes when the step closes.
 *
 *   npx tsx steps/loot/catalog.ts     writes steps/loot/build/<share>.md and steps/loot/build/code-support.md
 *
 * Each share's entries are copied with their kind and rarity, card, stats, numbers, code support and tags, and nothing else:
 * no notes, no closing sections. The code support is the spine's numbered list and each share's own list. Run it again after
 * any change to the fill; never edit the output by hand.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const SHARES = ["weapons-1", "weapons-2", "armor", "offhands-1", "offhands-2", "amulets", "formations", "versions-mythics"];
const KEEP = ["Is", "Card", "Stats", "Numbers", "Code", "Serves"];
const END = ["Challenges", "Links", "Loops", "Code support beyond the spine's list", "Least sure", "How this share is written"];
const OUT = "steps/loot/build";
mkdirSync(OUT, { recursive: true });

const sections = (text: string, heading: string): string => {
  const at = text.indexOf(`\n## ${heading}\n`);
  if (at < 0) return "";
  const rest = text.slice(at + heading.length + 5);
  const next = rest.search(/\n## /);
  return (next < 0 ? rest : rest.slice(0, next)).trim();
};

const support: string[] = [];
let total = 0;
for (const share of SHARES) {
  const text = readFileSync(`steps/loot/fill/${share}.md`, "utf8");
  const out: string[] = [`# ${share}: the catalog`, "", "Generated by `steps/loot/catalog.ts` from `fill/" + share + ".md`. Card, stats, numbers, code support and tags; the notes stay in the fill.", ""];
  let skip = false;
  let n = 0;
  for (const line of text.split("\n")) {
    const h2 = line.match(/^## (.+)$/);
    if (h2) { skip = END.includes(h2[1]); if (!skip) out.push("", line, ""); continue; }
    if (skip) continue;
    const h3 = line.match(/^### (.+)$/);
    if (h3) { out.push(line); n++; continue; }
    const f = line.match(/^- \*\*(\w+):\*\*/);
    if (f && KEEP.includes(f[1])) out.push(line);
  }
  total += n;
  writeFileSync(`${OUT}/${share}.md`, out.join("\n").replace(/\n{3,}/g, "\n\n").replace(/(\n- \*\*Serves:\*\*[^\n]*)\n(### )/g, "$1\n\n$2") + "\n");
  const own = sections(text, "Code support beyond the spine's list");
  if (own) support.push(`## From ${share}`, "", own, "");
}

const spine = readFileSync("steps/loot/spine.md", "utf8");
const a = spine.indexOf("### Code support");
const b = spine.indexOf("\n## ", a);
writeFileSync(`${OUT}/code-support.md`, [
  "# Code support",
  "",
  "Generated by `steps/loot/catalog.ts`: the spine's numbered list (a catalog entry's *Code* names these by number), then what each share's designer added. Hints from the design, not a plan: check each against the code and `PRIMITIVES.md`.",
  "",
  "## The spine's list",
  "",
  spine.slice(a + "### Code support".length, b).trim(),
  "",
  ...support,
].join("\n"));
console.log(`Wrote ${SHARES.length} catalog files (${total} entries) and code-support.md in ${OUT}/.`);
