// Builds a step's context pack: one file the director can paste into any chat,
// so an interviewer with no repo access has what it needs.
// Usage: npm run pack -- 4   (writes steps/04-.../pack.md from that folder's brief.md)
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const step = Number(process.argv[2]);
if (!Number.isInteger(step) || step < 1) throw new Error('Usage: npm run pack -- <step number>');

const prefix = String(step).padStart(2, '0') + '-';
const folder = readdirSync('steps').find((name) => name.startsWith(prefix));
if (!folder) throw new Error(`No steps/${prefix}* folder. Write the brief first.`);

const plan = readFileSync('docs/design-plan.md', 'utf8');
const entry = plan.match(new RegExp(`^### ${step}\\. [\\s\\S]*?(?=^### |^## |(?![\\s\\S]))`, 'm'));
if (!entry) throw new Error(`Step ${step} isn't in docs/design-plan.md.`);

const parts = [
  `# Step ${step} context pack\n\nEverything an interviewer needs for step ${step}, in one file. Generated by \`npm run pack -- ${step}\`; don't edit it by hand. Its parts: the primer, the interviewer guide, the step's entry in the design plan, and the brief.`,
  readFileSync('docs/primer.md', 'utf8'),
  readFileSync('docs/interviewer.md', 'utf8'),
  `# The step in the design plan\n\n${entry[0].trim()}`,
  readFileSync(`steps/${folder}/brief.md`, 'utf8'),
];

const out = `steps/${folder}/pack.md`;
writeFileSync(out, parts.map((part) => part.trim()).join('\n\n---\n\n') + '\n');
console.log(`Wrote ${out}`);
