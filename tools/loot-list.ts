/**
 * Today's loot as one line per item: every piece by slot and kind, the mythics, the formations with their seats, and every
 * ability's and passive's upgrade (its power step and two versions), each with its card text and the builds it was tagged for
 * (designer data, `PIECE_BUILDS`). It's for knowing what exists without reading the content's TypeScript: a design pass reads
 * it in place of `content/core-set/pieces/`, `formations.ts` and `upgrades/`, and a parallel fill can start its shared index
 * from it. Stats are left out (the interface shows them; the cards don't repeat them).
 *
 *   npx tsx tools/loot-list.ts [--out out/loot-list.md]
 *
 * Reads content/core-set.pack.json (run `npm run content` first if the content changed). Nothing here touches the engine.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { PIECE_BUILDS } from "../content/core-set/pieces/index.js";
import type { BuildTag } from "../content/core-set/pieces/kit.js";

type Text = { name: string; text: string };
type Piece = { id: string; name: string; text: string; slot: string; rarity?: string; weapon?: { kind: string }; armor?: string; offhand?: string; mythic?: string };
type Formation = { id: string; name: string; text: string; rarity: string; positions?: Text[] };
type Upgrade = { id: string; class: string; kind: string; power: string; a: Text; b: Text };
type Pack = { gear: Piece[]; formations: Formation[]; upgrades: Upgrade[]; abilities: { id: string; name: string }[]; classes: { id: string; name: string; passive?: { name: string } }[] };

const argOut = process.argv.indexOf("--out");
const out = argOut > 0 ? process.argv[argOut + 1] : "out/loot-list.md";
const pack: Pack = JSON.parse(readFileSync("content/core-set.pack.json", "utf8"));

const RARITIES = ["plain", "common", "uncommon", "rare", "legendary", "mythic"];
const dots = (n: number) => "●".repeat(n);
const tags = (id: string): string => {
  const t: BuildTag[] | undefined = PIECE_BUILDS[id];
  return t?.length ? ` · was tagged: ${t.map((b) => `${b.build}${b.rung ? ` ${b.rung}` : ""} ${dots(b.worth)}`).join(", ")}` : "";
};
const kindOf = (p: Piece) => p.weapon?.kind ?? p.armor ?? p.offhand ?? "amulet";
const words = (s: string) => s.replace(/_/g, " ");
const rarityOf = (p: Piece) => p.rarity ?? "plain";
const byRarity = (a: Piece, b: Piece) => RARITIES.indexOf(rarityOf(a)) - RARITIES.indexOf(rarityOf(b));
const className = new Map(pack.classes.map((c) => [c.id, c.name]));

const lines: string[] = ["# Today's loot, one line per item", "", "Generated by `tools/loot-list.ts` from `content/core-set.pack.json`. Card text as the player reads it; \"was tagged\" is the designer data of the twelve builds this loot was made for.", ""];
let counted = 0;

for (const slot of ["weapon", "armor", "offhand", "amulet"]) {
  const pieces = pack.gear.filter((p) => p.slot === slot && p.rarity !== "mythic");
  lines.push(`## ${slot === "armor" ? "Armor" : `${slot[0].toUpperCase()}${slot.slice(1)}s`} (${pieces.length})`, "");
  for (const kind of [...new Set(pieces.map(kindOf))]) {
    const ofKind = pieces.filter((p) => kindOf(p) === kind).sort(byRarity);
    if (slot !== "amulet") lines.push(`### ${words(kind)} (${ofKind.length})`, "");
    for (const p of ofKind) lines.push(`- **${p.name}** · ${rarityOf(p)} · ${p.text}${tags(p.id)}`);
    lines.push("");
    counted += ofKind.length;
  }
}

const mythics = pack.gear.filter((p) => p.rarity === "mythic");
lines.push(`## Mythics (${mythics.length})`, "");
for (const p of mythics) lines.push(`- **${p.name}** · ${className.get(p.mythic ?? "") ?? p.mythic} · ${p.slot} (${words(kindOf(p))}) · ${p.text}${tags(p.id)}`);
lines.push("");
counted += mythics.length;

lines.push(`## Formations (${pack.formations.length})`, "");
for (const r of ["common", "rare", "legendary"]) {
  for (const f of pack.formations.filter((x) => x.rarity === r)) {
    const seats = (f.positions ?? []).map((s) => `${s.name}: ${s.text ?? "nothing"}`).join(" / ");
    lines.push(`- **${f.name}** · ${f.rarity} · ${f.text}${seats ? ` · seats: ${seats}` : ""}${tags(f.id)}`);
  }
}
lines.push("");
counted += pack.formations.length;

lines.push(`## Upgrades (${pack.upgrades.length})`, "");
const abilityName = new Map(pack.abilities.map((a) => [a.id, a.name]));
for (const c of pack.classes) {
  const ups = pack.upgrades.filter((u) => u.class === c.id);
  if (!ups.length) continue;
  lines.push(`### ${c.name}`, "");
  for (const u of ups) {
    const name = u.kind === "passive" ? `${c.passive?.name ?? u.id} (passive)` : abilityName.get(u.id) ?? u.id;
    lines.push(`- **${name}** · power: ${u.power} · **A, ${u.a.name}:** ${u.a.text}${tags(`${u.id}__a`)} · **B, ${u.b.name}:** ${u.b.text}${tags(`${u.id}__b`)}`);
  }
  lines.push("");
}
counted += pack.upgrades.length;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n"));
console.log(`${counted} items (${pack.gear.length - mythics.length} pieces, ${mythics.length} mythics, ${pack.formations.length} formations, ${pack.upgrades.length} upgrades) → ${out}`);
