/**
 * The loot's shapes counted, one measure for a pass's before and after: how often the most repeated effect shapes appear on
 * the cards (gear, mythics, formations and upgrades, as `tools/loot-list.ts` lists them), the exotics and conditional pieces
 * among rares and legendaries (from the Serves lines, `SERVED`), each build's share of pieces whose card names its keyword,
 * the formations that name a build's keyword, and the reorienting versions (the upgrades' own marks). Then the alike-card
 * check: every pair of pieces one class can wear together whose cards share a sentence.
 *
 *   npx tsx tools/loot-count.ts [--pack content/core-set.pack.json] [--json out/loot-count.json]
 *
 * Reads the pack and the content modules' designer data, so run it where the two agree (`npm run content` first). For a
 * before count, run it in a checkout of the older commit.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import * as index from "../content/core-set/pieces/index.js";
import type { Tags } from "../content/core-set/pieces/kit.js";

type Text = { name: string; text: string };
type Piece = { id: string; name: string; text: string; slot: string; rarity?: string; source?: string; weapon?: { kind?: string; hands?: number }; armor?: string; offhand?: string; mythic?: string };
type Formation = { id: string; name: string; text: string; rarity: string; positions?: Text[] };
type Upgrade = { id: string; class: string; kind: string; power: string; a: Text; b: Text };
type Cls = { id: string; name: string; weapons: string[]; armor: string[]; offhands: string[] };
type Pack = { gear: Piece[]; formations: Formation[]; upgrades: Upgrade[]; classes: Cls[]; weaponKinds: { id: string; hands?: number }[] };

const arg = (k: string) => (process.argv.indexOf(k) > 0 ? process.argv[process.argv.indexOf(k) + 1] : undefined);
const pack: Pack = JSON.parse(readFileSync(arg("--pack") ?? "content/core-set.pack.json", "utf8"));
const SERVED: Record<string, Tags> = index.SERVED;
/** The upgrades' own marks, where the content has them (designer data): the versions that point an ability at another job. */
const REORIENTS: ReadonlySet<string> = new Set((index as { REORIENTS?: string[] }).REORIENTS ?? []);

// ─── The cards ──────────────────────────────────────────────────────────────

type Item = { id: string; kind: "piece" | "mythic" | "formation" | "upgrade"; rarity: string; text: string };
const items: Item[] = [
  ...pack.gear.filter((g) => g.source !== "starter").map((g): Item => ({ id: g.id, kind: g.rarity === "mythic" ? "mythic" : "piece", rarity: g.rarity ?? "plain", text: g.text })),
  ...pack.formations.map((f): Item => ({ id: f.id, kind: "formation", rarity: f.rarity, text: [f.text, ...(f.positions ?? []).map((s) => s.text ?? "")].join(" ") })),
  ...pack.upgrades.map((u): Item => ({ id: u.id, kind: "upgrade", rarity: "", text: [u.power, u.a.text, u.b.text].join(" ") })),
];

/** The shapes the kickoff counted, by the words on the card. */
const SHAPES: [string, RegExp][] = [
  ["Shield", /\bShields?\b/],
  ["Burn", /\bBurn/],
  ["Chill", /\bChill/],
  ["Shock", /\bShock/],
  ["Bleed", /\bBleed/],
  ["At fight start", /at fight start/i],
  ["On a kill or a foe falling", /\bkills?\b|\bfoe (?:that )?falls\b|\bfoe fell\b|\bfalls?:/i],
  ["A status on basic attacks", /basic attacks(?: and extra strikes)? (?:add|give|Weaken|Slow|Guard|Mark)/i],
  ["When hit", /when hit/i],
  ["Stun", /\bStun/],
  ["Thorns", /\bThorns/],
  ["A hit on every other foe", /every other foe/i],
];

/** Each build's keyword, as a player would pick the build by it (design.md, keyword share). */
const KEYWORD: Record<string, RegExp> = {
  landslide: /\bShields?\b/,
  cuts: /\bBleed/,
  bonfire: /\bBurn/,
  snap: /\bChill|shatter/i,
  storm: /\bShock/,
  hunt: /\bMark|\bkills?\b|\bfalls\b/i,
  toll: /\bThorns|when hit/i,
  barrage: /\bMP\b|\bfree\b|casts? (?:it )?again|cast twice/i,
  pact: /\bpays?\b|\bpaying\b|HP price|Lifesteal|below half/i,
};

const out: string[] = ["# The loot counted", "", "Generated by `tools/loot-count.ts`. Shapes by the words on the cards; exotics, conditional pieces and threads from the Serves lines.", ""];
const json: Record<string, unknown> = {};

out.push(`## Repeated shapes (${items.length} items: gear, mythics, formations, upgrades)`, "", "| Shape | Items |", "| --- | --- |");
const shapes: Record<string, number> = {};
for (const [name, re] of SHAPES) {
  shapes[name] = items.filter((x) => re.test(x.text)).length;
  out.push(`| ${name} | ${shapes[name]} |`);
}
json.shapes = shapes;

// ─── Exotics and conditional pieces ─────────────────────────────────────────

const high = pack.gear.filter((g) => g.rarity === "rare" || g.rarity === "legendary");
const exotic = (id: string) => !!SERVED[id] && (SERVED[id].other.includes("exotic") || !SERVED[id].builds.length);
const conditional = (id: string) => !!SERVED[id]?.other.includes("conditional");
const ex = high.filter((g) => exotic(g.id)), co = high.filter((g) => conditional(g.id));
out.push("", `## Rares and legendaries (${high.length})`, "", `- Exotic (no build served): ${ex.length}`, `- Conditional (a set-up the party makes): ${co.length}`, `- Both: ${high.filter((g) => exotic(g.id) && conditional(g.id)).length}`);
json.high = { all: high.length, exotic: ex.length, conditional: co.length };

// ─── Keyword share per build ────────────────────────────────────────────────

out.push("", "## Keyword share per build", "", "Of the pieces (mythics included) whose Serves line names the build at a rung, the share whose card names the build's keyword.", "", "| Build | Pieces | Name the keyword | Share |", "| --- | --- | --- | --- |");
const share: Record<string, { pieces: number; keyword: number }> = {};
for (const [build, re] of Object.entries(KEYWORD)) {
  const mine = pack.gear.filter((g) => SERVED[g.id]?.builds.some((t) => t.build === build && t.rung));
  const named = mine.filter((g) => re.test(g.text));
  share[build] = { pieces: mine.length, keyword: named.length };
  out.push(`| ${build} | ${mine.length} | ${named.length} | ${mine.length ? Math.round((100 * named.length) / mine.length) : 0}% |`);
}
json.keywordShare = share;

// ─── Formations ─────────────────────────────────────────────────────────────

const themed = pack.formations.filter((f) => {
  const text = [f.text, ...(f.positions ?? []).map((s) => s.text ?? "")].join(" ");
  return Object.entries(KEYWORD).some(([b, re]) => b !== "barrage" && b !== "pact" && b !== "hunt" && re.test(text)) || /\bMarks?\b/.test(text);
});
out.push("", `## Formations (${pack.formations.length})`, "", `- Naming a status road's keyword, Shield, Thorns or a Mark on a card or seat: ${themed.length} (${themed.map((f) => f.name).join(", ")})`);
json.formations = { all: pack.formations.length, themed: themed.length };

// ─── Upgrades ───────────────────────────────────────────────────────────────

const abilitiesUp = pack.upgrades.filter((u) => u.kind === "ability");
const turning = abilitiesUp.filter((u) => REORIENTS.has(`${u.id}__a`) || REORIENTS.has(`${u.id}__b`));
out.push("", `## Upgrades (${pack.upgrades.length})`, "", REORIENTS.size ? `- Abilities with a reorienting version (marked in the content): ${turning.length} of ${abilitiesUp.length}` : "- Reorienting versions: not marked in this content");
json.reorienting = REORIENTS.size ? turning.length : null;

// ─── Alike cards ────────────────────────────────────────────────────────────

/** A card's sentences, as a player reads them; a plain card has none worth comparing. */
const sentences = (t: string) => t.split(/(?<=[.!?])\s+/).map((s) => s.trim().toLowerCase()).filter((s) => s.length > 12 && s !== "nothing beyond its stats.");
const hands = (g: Piece) => g.weapon?.hands ?? pack.weaponKinds.find((k) => k.id === g.weapon?.kind)?.hands ?? 1;
const wears = (c: Cls, g: Piece) =>
  g.mythic ? g.mythic === c.id : g.slot === "amulet" || (g.slot === "weapon" && !!g.weapon?.kind && c.weapons.includes(g.weapon.kind)) || (g.slot === "armor" && !!g.armor && c.armor.includes(g.armor)) || (g.slot === "offhand" && !!g.offhand && c.offhands.includes(g.offhand));
const alike = new Map<string, string>();
for (const c of pack.classes) {
  const mine = pack.gear.filter((g) => g.source !== "starter" && wears(c, g));
  for (let i = 0; i < mine.length; i++)
    for (let j = i + 1; j < mine.length; j++) {
      const a = mine[i], b = mine[j];
      if (a.slot === b.slot) continue;
      if ((a.slot === "weapon" && b.slot === "offhand" && hands(a) === 2) || (b.slot === "weapon" && a.slot === "offhand" && hands(b) === 2)) continue;
      const sa = sentences(a.text), sb = new Set(sentences(b.text));
      const same = sa.find((s) => sb.has(s));
      if (!same) continue;
      const key = [a.name, b.name].sort().join(" + ");
      alike.set(key, `${alike.get(key) ? `${alike.get(key)}, ` : ""}${c.name}: "${same}"`.replace(/^(.*?, )?/, (m) => m));
    }
}
out.push("", `## Alike cards (${alike.size} pairs)`, "", "Pairs of pieces one class can wear together whose cards share a sentence.", "", ...[...alike].map(([k, v]) => `- ${k} · ${v}`));
json.alike = [...alike.keys()];

const file = arg("--out") ?? "out/loot-count.md";
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, out.join("\n") + "\n");
if (arg("--json")) writeFileSync(arg("--json")!, JSON.stringify(json, null, 1));
console.log(out.join("\n"));
