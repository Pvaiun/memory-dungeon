/**
 * Builds the core set's content pack from the generator files beside it and
 * writes content/core-set.pack.json, after validating it.
 *
 *   npm run content
 *
 * Every number comes from scale.ts: change a constant there, rebuild, and the
 * studies read the new pack. The generated JSON is committed, so the engine,
 * the tests and the studies read plain data as they always have.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import type { ContentPack } from "../../src/schema.js";
import { validatePack } from "../../src/validate.js";
import { abilities, classes, passives } from "./classes.js";
import { dungeons } from "./dungeons.js";
import { enemies, enemyAbilities, enemyStatuses } from "./enemies.js";
import { effects, formations } from "./formations.js";
import { gear } from "./gear.js";
import { design, elements, machinery, ruleset, stats, vocabulary, weaponKinds } from "./vocabulary.js";

export function buildPack(): unknown {
  const pack: ContentPack = {
    schemaVersion: "0.6",
    id: "core_set",
    title: "The core set",
    note: "Generated by content/core-set/build.ts from the generator files beside it. Don't edit by hand: change scale.ts or the content files and run npm run content. Every number is a first value, placeholder until the balance pass.",
    design,
    ruleset,
    stats,
    elements,
    weaponKinds,
    statuses: [...vocabulary, ...machinery, ...passives, ...effects, ...enemyStatuses],
    classes,
    abilities: [...abilities, ...enemyAbilities],
    gear,
    formations,
    enemies,
    perkFamilies: [],
    perks: [],
    dungeons,
    starter: {
      classes: classes.filter((c) => c.source === "starter").map((c) => c.id),
      formations: formations.filter((f) => f.source === "starter").map((f) => f.id),
      gear: gear.filter((g) => g.source === "starter").map((g) => g.id),
    },
    progression: { dungeonOrder: dungeons.map((d) => d.id) },
  };
  return JSON.parse(JSON.stringify(pack));
}

const raw = buildPack();
const result = validatePack(raw);
for (const i of result.issues) console.log(`  ${i.level === "error" ? "ERROR" : "warn "} [${i.code}] ${i.path}: ${i.message}`);
if (result.errors) {
  console.error(`✗ ${result.errors} errors; not written`);
  process.exit(1);
}
mkdirSync("content", { recursive: true });
writeFileSync("content/core-set.pack.json", JSON.stringify(raw, null, 1) + "\n");
const p = result.pack!;
console.log(`✓ content/core-set.pack.json: ${p.classes.length} classes, ${p.abilities.length} abilities, ${p.statuses.length} statuses, ${p.gear.length} gear, ${p.formations.length} formations, ${p.enemies.length} enemies, ${p.dungeons.length} dungeons; ${result.warnings} warnings`);
