/**
 * The authored-gaps step's web, counted from its own page: `steps/authored-gaps/web.md` holds the list of threads and a
 * catalog row for every effect, written as what it wants and what it gives. This checks every word in the catalog against
 * the list, and prints what the page's count is judged from: how many effects give, want and name each thread, the threads
 * nothing gives or nothing wants, which threads the effects join, how many partners each effect has, and how often a
 * partner turns up when a run shows a fifth of the web.
 *
 *   npx tsx tools/web-threads.ts [--out out/web-threads.md]
 *
 * Two effects are partners when one gives a thread the other wants. An effect that gives a thread also takes on what that
 * thread wants and gives by the rules (the list's last column). The threads every unit has are left out of partners and joins.
 * The page is read by `web-threads/read.ts`; `web-map.ts` draws the same web.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { PAGE, readWeb } from "./web-threads/read.js";

const SHARE_SEEN = 5; // a run shows about a fifth of the loot
const LINE = 12; // one effect in twelve naming a thread is the overuse line

let web;
try {
  web = readWeb();
} catch (e) {
  console.error((e as Error).message);
  process.exit(1);
}
const { threads, common, effects } = web;
const byName = new Map(threads.map((t) => [t.name, t]));

/** What an effect wants and gives once the rules of the threads it gives are counted, without the threads every unit has. */
const reach = effects.map((e) => {
  const given = e.gives.map((g) => byName.get(g)!);
  const specific = (ws: string[]) => new Set(ws.filter((w) => !common.has(w)));
  return { wants: specific([...e.wants, ...given.flatMap((t) => t.wants)]), gives: specific([...e.gives, ...given.flatMap((t) => t.gives)]) };
});
const meets = (a: Set<string>, b: Set<string>) => [...a].some((w) => b.has(w));
const partners = effects.map((_, i) => effects.flatMap((_, j) => (i !== j && (meets(reach[i].gives, reach[j].wants) || meets(reach[i].wants, reach[j].gives)) ? [j] : [])));

/** The chance that at least one of k partners is among the rest of a run's share of the web. */
function seen(k: number): number {
  const others = effects.length - 1;
  const shown = Math.round(effects.length / SHARE_SEEN) - 1;
  let none = 1;
  for (let i = 0; i < shown; i++) none *= (others - k - i) / (others - i);
  return 1 - Math.max(0, none);
}

const out: string[] = [`# The web's threads, counted`, "", `Generated by \`tools/web-threads.ts\` from \`${PAGE}\`: ${effects.length} effects on ${threads.length} threads. The overuse line is one effect in ${LINE}: ${Math.ceil(effects.length / LINE)}.`, ""];

out.push("## The tally", "", "| Thread | Gives | Wants | Names it | By its own name | By a word for several |", "| --- | --- | --- | --- | --- | --- |");
const tally = threads.map((t) => {
  const gives = effects.filter((e) => e.gives.includes(t.name));
  const wants = effects.filter((e) => e.wants.includes(t.name));
  const names = new Set([...gives, ...wants]);
  return { t, gives: gives.length, wants: wants.length, names: names.size, grouped: [...names].filter((e) => e.grouped.includes(t.name)).length };
});
for (const r of tally) out.push(`| ${r.t.name}${common.has(r.t.name) ? " (every unit's)" : ""} | ${r.gives} | ${r.wants} | ${r.names} | ${r.names - r.grouped} | ${r.grouped || ""} |`);
const names = (rs: typeof tally) => rs.map((r) => r.t.name).join(", ") || "none";
out.push("", `- **Nothing gives it:** ${names(tally.filter((r) => !r.gives && r.wants))}.`, `- **Nothing wants it:** ${names(tally.filter((r) => r.gives && !r.wants))}.`, `- **Nothing names it:** ${names(tally.filter((r) => !r.names))}.`, "");

out.push("## What joins what", "", "For each thread, where the effects that want it lead (what they give), and where it's fed from (what the effects that give it want), with what each thread does by the rules counted in. The number is how many effects make the join.", "");
for (const t of threads.filter((t) => !common.has(t.name))) {
  const own = new Set([t.name, ...t.wants, ...t.gives]);
  const join = (side: "wants" | "gives", other: "wants" | "gives") => {
    const n = new Map<string, number>();
    effects.forEach((_, i) => reach[i][side].has(t.name) && reach[i][other].forEach((w) => !own.has(w) && n.set(w, (n.get(w) ?? 0) + 1)));
    return [...n].sort((a, b) => b[1] - a[1]).map(([w, c]) => `${w} ${c}`).join(", ") || "nothing";
  };
  out.push(`- **${t.name}** leads to: ${join("wants", "gives")}. Fed from: ${join("gives", "wants")}.`);
}

const withBoth = effects.filter((e) => e.wants.length && e.gives.length);
const across = withBoth.filter((e) => e.gives.some((g) => !e.wants.includes(g)));
const alone = effects.filter((_, i) => !partners[i].length);
const mean = (xs: number[]) => xs.reduce((a, b) => a + b, 0) / xs.length;
const sorted = partners.map((p) => p.length).sort((a, b) => a - b);
out.push("", "## The effects", "",
  `- **Want one thread and give a different one:** ${across.length} of ${effects.length}. Give nothing (a payoff): ${effects.filter((e) => !e.gives.length).length}. Want nothing: ${effects.filter((e) => !e.wants.length).length}.`,
  `- **Cross from one unit to another:** ${effects.filter((e) => e.crosses).length}.`,
  `- **Partners:** ${sorted[sorted.length >> 1]} for the middle effect, from ${sorted[0]} to ${sorted[sorted.length - 1]}.`,
  `- **With a fifth of the web shown,** an effect has a partner shown too ${Math.round(100 * mean(partners.map((p) => seen(p.length))))}% of the time.`,
  `- **No partner** (${alone.length}): only the threads every unit has, or a thread nothing else touches.`, ...alone.map((e) => `  - ${e.name}`),
  "", "| Effect | From | Partners |", "| --- | --- | --- |", ...effects.map((e, i) => `| ${e.name} | ${e.from} | ${partners[i].length} |`), "");

const argOut = process.argv.indexOf("--out");
const path = argOut > 0 ? process.argv[argOut + 1] : "out/web-threads.md";
mkdirSync(dirname(path), { recursive: true });
writeFileSync(path, out.join("\n"));
console.log(out.slice(0, out.indexOf("| Effect | From | Partners |") - 1).join("\n"));
console.log(`\nWritten to ${path}, with each effect's partners.`);
